"""Small derived tables for figures that combine results from several stages."""
import json
from common import *
P = json.loads((RES / "preflight.json").read_text()); D = json.loads((RES / "diag.json").read_text()); A = json.loads((RES / "analyzer.json").read_text())
T = A["timer"]
# cross-instrument agreement: on-chip cycle counter (x) against logic analyzer (y); different trials, same condition
rows = [
 ("warm load",        P["warm"]["work_modes"][0]["us"],      T["warm"]["a1_no"]["p50"],     T["warm"]["legacy_a1_median"]),
 ("two-line load",    P["two"]["work_modes"][0]["us"],       T["two"]["a1_no"]["p50"],      T["two"]["legacy_a1_median"]),
 ("eight-line load",  P["eight"]["work_modes"][0]["us"],     T["eight"]["a1_no"]["p50"],    T["eight"]["legacy_a1_median"]),
 ("sixteen-line load",P["sixteen"]["work_modes"][0]["us"],   T["sixteen"]["a1_no"]["p50"],  T["sixteen"]["legacy_a1_median"]),
 ("baseline latency", P["baseline"]["lat"]["p50"],           T["base01"]["lat"]["p50"],     float("nan")),
 ("UART frame, 16 B", P["intr16"]["wall"]["p50"],            A["uart"]["16"]["a0_us"],      float("nan")),
 ("SPI queue, first", P["dma_pre"]["queue_first"],           A["spi"]["spi11"]["queue_us"], float("nan")),
 ("SPI queue, later", P["dma_pre"]["queue_rest"]["mean"],    0.5 * (A["spi"]["d2"]["queue_us"] + A["spi"]["d3"]["queue_us"]), float("nan")),
 ("register, shallow",P["spill"]["resident"][0] * 1000 / CPU_MHZ, A["reg"]["widths_us"][0], A["reg"]["legacy_widths_us"][0]),
 ("register, forced", P["spill"]["forced"][0] * 1000 / CPU_MHZ,   A["reg"]["widths_us"][2], A["reg"]["legacy_widths_us"][2]),
 ("register, deep",   P["spill"]["deep"][0] * 1000 / CPU_MHZ,     A["reg"]["widths_us"][1], A["reg"]["legacy_widths_us"][1]),
]
write_dat("xcheck.dat", ["onchip", "ext", "legacy"], [(r[1], r[2], r[3]) for r in rows])
X = {"rows": [{"label": r[0], "onchip": r[1], "ext": r[2], "legacy": None if r[3] != r[3] else r[3],
               "rel_pct": 100 * (r[2] - r[1]) / r[1], "legacy_rel_pct": None if r[3] != r[3] else 100 * (r[3] - r[1]) / r[1]} for r in rows]}
X["max_abs_rel_pct"] = max(abs(r["rel_pct"]) for r in X["rows"])
X["max_abs_rel_pct_excl_warm"] = max(abs(r["rel_pct"]) for r in X["rows"] if r["label"] != "warm load")
X["legacy_max_abs_rel_pct"] = max(abs(r["legacy_rel_pct"]) for r in X["rows"] if r["legacy_rel_pct"] is not None)
# diag on-chip vs 12-Nov analyzer (different sessions, same firmware family)
pairs = [("c50on", "cache50_on"), ("c50off", "cache50_off"), ("c100on", "cache100_on"), ("c100off", "cache100_off")]
X["diag_pairs"] = [{"cap": a, "cond": b, "ext_no": T[a]["a1_no"]["mean"], "chip_no": D[b]["load_noisr"]["mean"],
                    "ext_frac_pct": 100 * T[a]["frac_isr"], "chip_frac_pct": 100 * D[b]["frac_isr_load"],
                    "ext_lead": T[a]["lead"]["p50"], "chip_flush": D[b]["flush"]["p50"],
                    "ext_cb": T[a]["a3"]["mean"], "chip_cb": D[b]["cb"]["mean"],
                    "ext_absjit": T[a]["a2_absjit"]["mean"], "chip_absjit": D[b]["absjit"]["mean"]} for a, b in pairs]
write_dat("flush_ext.dat", ["pat", "absjit_on", "absjit_off", "load_on", "load_off"],
          [(1, T["c50on"]["a2_absjit"]["mean"], T["c50off"]["a2_absjit"]["mean"], T["c50on"]["a1_no"]["mean"], T["c50off"]["a1_no"]["mean"]),
           (2, T["c100on"]["a2_absjit"]["mean"], T["c100off"]["a2_absjit"]["mean"], T["c100on"]["a1_no"]["mean"], T["c100off"]["a1_no"]["mean"])])
save_results("xcheck", X)
for r in X["rows"]: print(f"{r['label']:20s} chip {r['onchip']:10.3f} ext {r['ext']:10.3f} ({r['rel_pct']:+.2f}%) legacy {r['legacy']}")
print(X["max_abs_rel_pct"], X["max_abs_rel_pct_excl_warm"], X["legacy_max_abs_rel_pct"])
for p in X["diag_pairs"]: print({k: (round(v, 3) if isinstance(v, float) else v) for k, v in p.items()})

# label macros generated from the decoded bytes (so annotations cannot drift from the data)
lines = (DATA / "wf_poll_bytes.dat").read_text().split("\n")[1:]
with open(DATA / "wf_poll_labels.tex", "w") as fh:
    fh.write("% generated by p4_figdata.py from the decoded wire bytes of Polling_01.alc\n")
    for l in lines:
        if not l.strip(): continue
        t, idx, got, exp = l.split()
        fh.write(f"\\bytelabel{{{t}}}{{{idx}}}{{{got}}}{{{exp}}}\n")
lines = (DATA / "wf_spiz_bytes.dat").read_text().split("\n")[1:]
with open(DATA / "wf_spiz_labels.tex", "w") as fh:
    fh.write("% generated by p4_figdata.py from the decoded MOSI bytes of SPI_DMA_01.alc\n")
    for l in lines:
        if not l.strip(): continue
        t, hx = l.split()
        fh.write(f"\\spibyte{{{t}}}{{{hx}}}\n")
c = A["reg"]["cycles_per_iter"]
write_dat("reg_bars.dat", ["x", "cyc"], [(1, c[0]), (2, c[2]), (3, c[1])])
