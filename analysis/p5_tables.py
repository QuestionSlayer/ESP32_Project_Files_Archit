"""Appendix tables generated from the same results as the main text."""
import json, csv
from common import *
A = json.loads((RES / "analyzer.json").read_text())

def esc(s): return s.replace("_", r"\_")

# capture inventory (longtable body)
rows = list(csv.DictReader(open(VALID / "analyzer_inventory.csv")))
rows.sort(key=lambda r: (r["acq"][6:8], r["acq"][0:5], r["acq"][9:]))
with open(DATA / "tab_inventory.tex", "w") as fh:
    fh.write("% generated by p5_tables.py from validation/analyzer_inventory.csv\n")
    for r in rows:
        name = r["file"].split("/")[-1].replace(".alc", "")
        folder = "/".join(r["file"].split("/")[:-1]) or "--"
        e = json.loads(r["edges"].replace("'", '"')) if r["edges"].startswith("[") else []
        active = "A" + ",".join(str(i) for i, n in enumerate(e) if n > 0)
        fh.write(f"S{'2' if r['session']=='11-Nov' else '3'} & {r['acq'][9:]} & \\code{{{name}}} & "
                 f"{float(r['rate_mhz']):g} & {r['trigger_record']} & {r['pretrigger_garbage_records']} & "
                 f"{float(r['valid_ms']):.1f} & {active} & \\code{{{r['sha256'][:8]}}} \\\\\n")

# run acceptance summary
acc = list(csv.DictReader(open(VALID / "run_acceptance.csv")))
with open(DATA / "tab_acceptance.tex", "w") as fh:
    fh.write("% generated by p5_tables.py from validation/run_acceptance.csv\n")
    names = {"stress1": "baseline (\\cmd{1})", "stress5": "worker at 22 (\\cmd{5})", "cache_warm": "warm (\\cmd{u})",
             "cache12": "two-line (\\cmd{m})", "cache50": "eight-line (\\cmd{t})", "cache100": "sixteen-line (\\cmd{7})"}
    for t, lab in names.items():
        rr = [r for r in acc if r["test"] == t]
        ok = [r for r in rr if r["accepted"] == "True"]
        ev = sum(int(r["rows"]) for r in ok)
        bad = "; ".join(f"run {r['repeat']}: {r['reason']}" for r in rr if r["accepted"] != "True") or "--"
        fh.write(f"{lab} & {len(rr)} & {len(ok)} & {ev} & {min(int(r['rows']) for r in ok)}--{max(int(r['rows']) for r in ok)} & {bad} \\\\\n")
    fh.write("\\bottomrule\n")
print("tables written")
